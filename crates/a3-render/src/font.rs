/// Atlas index of the glyph drawn for `c`: lower case shares the upper-case glyphs, characters
/// without a glyph draw as `?`.
pub fn glyph_index(c: char) -> u32 {
    let c = c.to_ascii_uppercase();
    if GLYPHS.iter().any(|(g, _)| *g == c) {
        c as u32 - 32
    } else {
        '?' as u32 - 32
    }
}

/// The font atlas as one byte (0 or 255) per pixel, `ATLAS_W` x `ATLAS_H`, row-major.
pub fn atlas() -> Vec<u8> {
    let mut pixels = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
    for (c, rows) in GLYPHS {
        let index = *c as u32 - 32;
        let (cx, cy) = (
            index % ATLAS_COLUMNS * CELL_W,
            index / ATLAS_COLUMNS * CELL_H,
        );
        for (y, row) in rows.iter().enumerate() {
            for (x, ch) in row.chars().enumerate() {
                if ch == '#' {
                    let px = cx + x as u32;
                    let py = cy + y as u32;
                    pixels[(py * ATLAS_W + px) as usize] = 255;
                }
            }
        }
    }
    pixels
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (c, rows) in GLYPHS {
            assert!(rows.iter().all(|r| r.chars().count() == 5), "glyph {c:?}");
            assert!((' '..='~').contains(c));
        }
    }

    #[test]
    fn lower_case_and_unknown_characters_fall_back() {
        assert_eq!(glyph_index('a'), glyph_index('A'));
        assert_eq!(glyph_index('~'), glyph_index('?'));
        assert_eq!(glyph_index('0'), 16);
    }

    #[test]
    fn atlas_places_glyph_pixels_in_their_cell() {
        let a = atlas();
        // 'I' (index 41: column 9, row 2) has its top bar at x 1..4 of the cell.
        let (cx, cy) = (9 * CELL_W, 2 * CELL_H);
        let at = |x: u32, y: u32| a[((cy + y) * ATLAS_W + cx + x) as usize];
        assert_eq!((at(0, 0), at(1, 0), at(3, 0), at(4, 0)), (0, 255, 255, 0));
        assert_eq!(at(2, 3), 255);
        // Space is empty.
        assert!(a[..(CELL_W as usize)].iter().all(|&p| p == 0));
    }
}
